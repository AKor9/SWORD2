using System.Numerics;

namespace Sword.Game.Contracts;

/// <summary>
/// Оружие бойца в мире после тика — простые данные для клиентских модулей представления (огонь на головке факела), без мира ECS:
/// <see cref="Key"/> — боец (номер и поколение сущности: место строится заново — сброс R, возрождение, команда сцены — на той же сущности,
/// поэтому ключ тот же и после смерти, и после постройки заново; новый — только у нового места),
/// <see cref="Slot"/> — место (0 — игрок), <see cref="Weapon"/> — номер таблицы оружия, <see cref="Tip"/> и <see cref="Base"/> — кончик и
/// основание клинка в мире (кончик — самая дальняя от кисти вершина меша: у факела — головка), <see cref="Alive"/> — боец жив,
/// <see cref="Dropped"/> — оружие не в руке (выпало при смерти и лежит на теле клинка трупа), <see cref="Built"/> — боец построен в этом
/// тике (новое место или постройка заново на той же сущности — сброс R, возрождение, команда сцены: ключ тот же, а головка «прыгает»
/// на новое место — всё, что велось по тикам, начинается заново).
/// </summary>
public readonly record struct WeaponTip(ulong Key, int Slot, bool IsPlayer, int Weapon, Vector3 Base, Vector3 Tip, bool Alive, bool Dropped,
    bool Built);

/// <summary>
/// Оружие бойцов тика для клиентских модулей (сервис клиента — <c>ClientServices</c>): читает мир в момент вызова, поэтому из наблюдателя
/// тиков клиента (<c>ClientBuilder.AfterTick</c>) — состояние после своего тика, не кадра. Реализует клиентская часть игры, отдаёт модулям exe;
/// только чтение — ни симуляции, ни хеша, ни реплея не касается.
/// </summary>
public interface IWeaponTips
{
    /// <summary>Оружия в таблице (номера 0 … N − 1; до постройки мира — 0).</summary>
    int WeaponCount { get; }

    /// <summary>Имя оружия (файл пака без расширения: <c>sword_1h</c>, позже <c>torch</c>).</summary>
    string WeaponName(int weapon);

    /// <summary>Номер оружия по имени без учёта регистра; нет — −1.</summary>
    int FindWeapon(string name);

    /// <summary>
    /// Оружие бойцов после последнего сыгранного тика — по одному на бойца с оружием, в порядке мира; вернёт, сколько их всего (записано не
    /// больше <paramref name="into"/>.Length). Без выделений.
    /// </summary>
    int Read(Span<WeaponTip> into);
}
